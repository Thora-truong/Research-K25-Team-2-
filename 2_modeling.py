# 2. HEURISTIC: GREEDY-ADD + ONE-SWAP (Vectorized)
# =============================================================================
class HeuristicSolver:
    def __init__(self, max_iter=10_000, tol=1e-9):
        self.max_iter = max_iter
        self.tol = tol

    def solve(self, cost_matrix, K, weights=None):
        C = apply_weights(cost_matrix, weights)
        I, J = C.shape
        check_K(K, J)
        ids = np.array(cost_matrix.columns)

        t0 = time.perf_counter()

        # Stage 1: Greedy-Add
        S = []
        cur_cost = np.full(I, np.inf)
        for _ in range(K):
            closed = np.setdiff1d(np.arange(J), S)
            Z = np.minimum(cur_cost[:, None], C[:, closed]).sum(axis=0)
            j = int(closed[np.argmin(Z)])
            S.append(j)
            cur_cost = np.minimum(cur_cost, C[:, j])

        greedy_obj = float(cur_cost.sum())
        obj = greedy_obj

        # Stage 2: One-Swap (Best-improvement)
        it = 0
        while it < self.max_iter:
            closed = np.setdiff1d(np.arange(J), S)
            if closed.size == 0:
                break

            threshold = obj - self.tol * max(1.0, abs(obj))   # Relative threshold
            best_move, best_z = None, threshold

            for pos, out_j in enumerate(S):
                rest = S[:pos] + S[pos + 1:]
                base = C[:, rest].min(axis=1) if rest else np.full(I, np.inf)
                Z = np.minimum(base[:, None], C[:, closed]).sum(axis=0)
                k = int(np.argmin(Z))

                if Z[k] < best_z:
                    best_z, best_move = float(Z[k]), (pos, int(closed[k]))

            if best_move is None:
                break

            S[best_move[0]] = best_move[1]
            obj = best_z
            it += 1

        return {
            "method": "Heuristic", "K": K,
            "objective": float(obj),
            "greedy_objective": greedy_obj,
            "selected_facilities": ids[S].tolist(),
            "swap_iterations": it,
            "runtime_sec": time.perf_counter() - t0,
        }

