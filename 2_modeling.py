# build_cost: tao cost matrix voi fallback + scale + distance multiplier
# ═══════════════════════════════════════════════════════════
def build_cost(dist_df_, fallback, scale=1.0):
    """c_ij = scale * (alpha + beta * d_ij); curve theo DC state."""
    C = np.zeros(dist_df_.shape)
    for j, dc in enumerate(dist_df_.columns):
        st = fallback.get(DC_STATE[dc], DC_STATE[dc])
        bands = CURVE[st]
        d = dist_df_.values[:, j]
        last = bands[-1]
        ic = np.full_like(d, last[1])
        sl = np.full_like(d, last[2])
        for k, (mode, a, b, lo, hi) in enumerate(bands):
            is_last = (k == len(bands) - 1)
            m = (d >= lo) if is_last else ((d >= lo) & (d < hi))
            ic[m], sl[m] = a, b
        C[:, j] = scale * (ic + sl * d)
    return pd.DataFrame(C, index=dist_df_.index, columns=dist_df_.columns)


