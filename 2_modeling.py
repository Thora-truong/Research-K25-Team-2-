class ExactMILPSolver:
    """
    min  sum_ij c_ij x_ij
    s.t. sum_j x_ij = 1     (each branch assigned to exactly 1 DC)
         x_ij <= y_j        (cannot assign to closed DC)
         sum_j y_j = K      (exactly K DCs are opened)
         x, y in {0,1}
    """
    def __init__(self, time_limit=900, mip_gap=0.0):
        self.time_limit = time_limit
        self.mip_gap = mip_gap
        self.solver_name = "SciPy HiGHS"

    def _build(self, I, J, K):
        nx = I * J
        n_var = nx + J

        # (1) sum_j x_ij = 1
        A_assign = csr_matrix(
            (np.ones(nx), (np.repeat(np.arange(I), J), np.arange(nx))),
            shape=(I, n_var))

        # (3) sum_j y_j = K
        A_card = csr_matrix(
            (np.ones(J), (np.zeros(J, dtype=int), nx + np.arange(J))),
            shape=(1, n_var))

        A_eq = vstack([A_assign, A_card]).tocsr()
        b_eq = np.append(np.ones(I), K)

        # (2) x_ij - y_j <= 0
        rows = np.repeat(np.arange(nx), 2)
        cols = np.empty(2 * nx, dtype=int)
        vals = np.empty(2 * nx)

        cols[0::2] = np.arange(nx)
        vals[0::2] = 1.0
        cols[1::2] = nx + np.tile(np.arange(J), I)
        vals[1::2] = -1.0

        A_link = csr_matrix((vals, (rows, cols)), shape=(nx, n_var))

        return [LinearConstraint(A_eq, b_eq, b_eq),
                LinearConstraint(A_link, -np.inf, 0)]

    def solve(self, cost_matrix, K, weights=None):
        C = apply_weights(cost_matrix, weights)
        I, J = C.shape
        check_K(K, J)
        ids = list(cost_matrix.columns)

        constraints = self._build(I, J, K)          # Build outside solver timer
        c_obj = np.concatenate([C.ravel(), np.zeros(J)])

        t0 = time.perf_counter()                    # Start solver timer
        res = milp(
            c=c_obj,
            constraints=constraints,
            integrality=np.ones(I * J + J),
            bounds=Bounds(0, 1),
            options={"time_limit": float(self.time_limit),
                     "mip_rel_gap": float(self.mip_gap),
                     "disp": False},
        )
        runtime = time.perf_counter() - t0

        if res.x is None:
            raise RuntimeError(f"MILP K={K}: No feasible solution found ({res.message}).")

        y = res.x[I * J:]
        selected = [ids[j] for j in np.where(y > 0.5)[0]]

        gap = getattr(res, "mip_gap", None)
        bound = getattr(res, "mip_dual_bound", None)
        gap = float(gap) if gap is not None and np.isfinite(gap) else np.nan
        bound = float(bound) if bound is not None and np.isfinite(bound) else np.nan

        if res.status == 0 and (np.isnan(gap) or gap <= 1e-9):
            status = "Optimal"
        elif res.status == 0:
            status = "Optimal within gap tolerance"
        else:
            status = "Time limit (feasible)"

        return {
            "method": "MILP", "K": K,
            "objective": float(res.fun),
            "selected_facilities": selected,
            "solver": self.solver_name,
            "status": status,
            "best_bound": bound,
            "optimality_gap": gap,
            "runtime_sec": runtime,
        }

