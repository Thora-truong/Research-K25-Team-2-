def apply_weights(cost_matrix, weights=None):
    """
    Returns a numpy cost matrix (I x J), multiplied by branch weights.
    weights: pd.Series (index = branch) or None. Normalized to mean = 1.
    """
    C = cost_matrix.values.astype(float)
    if weights is None:
        return C

    w = weights.reindex(cost_matrix.index)
    if w.isna().any():
        raise ValueError("Weights are missing values for some branches.")

    w_mean = w.mean()
    if w_mean == 0:
        raise ValueError("Mean of weights cannot be zero.")

    w = (w / w_mean).values
    return C * w[:, None]

def check_K(K, J):
    if not (1 <= K <= J):
        raise ValueError(f"Invalid K={K}, must be between 1 and {J}.")

