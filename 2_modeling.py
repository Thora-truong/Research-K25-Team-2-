class SharedEvaluator:
    """
    Evaluates a set S of open DCs.
    Branches are always assigned to their cheapest open DC (same rule for
    every algorithm), so results are comparable across methods.

    Weights never change the assignment (argmin_j w_i*c_ij = argmin_j c_ij);
    they only change the delivery objective, which also decides which S the
    MILP / heuristic picks.

    Use evaluate() for final solutions (full validation + all metrics).
    Use fast_delivery() inside heuristic loops (numpy only, no pandas).
    """

    def __init__(self, cost_matrix, dist_matrix, demand_series,
                 i_bar, s_rate, h_rate,
                 w_svc=None, cbm_for_handling=None):
        self.C = cost_matrix
        self.D = dist_matrix

        # One-time data checks
        if not self.C.index.equals(self.D.index) or not self.C.columns.equals(self.D.columns):
            raise ValueError("cost and distance matrices must share the same index and columns")
        if not np.isfinite(self.D.values).all():
            raise ValueError("Bad distances (NaN/Inf)")
        if (self.D.values < 0).any():
            raise ValueError("Negative distances")
        if not np.isfinite(self.C.values).all():
            raise ValueError("Bad costs (NaN/Inf)")
        if (self.C.values < 0).any():
            raise ValueError("Negative costs")
        if not self.C.index.is_unique:
            raise ValueError("Duplicate branch ids in cost matrix")
        if not self.C.columns.is_unique:
            raise ValueError("Duplicate DC ids in cost matrix")

        # Align every per-branch series to the cost matrix index
        def _align(series, name):
            if series is None:
                return None
            missing = set(self.C.index) - set(series.index)
            if missing:
                raise ValueError(f"{name} missing for {len(missing)} branches, e.g. {list(missing)[:3]}")
            s = series.reindex(self.C.index)
            if s.isna().any():
                raise ValueError(f"NaN in {name}")
            return s.astype(float)

        # demand is required
        self.q = _align(demand_series, "demand_series")
        if self.q is None:
            raise ValueError("demand_series is required")

        # Service weights and handling CBM default to demand, but can differ
        self.w_svc = _align(w_svc, "w_svc") if w_svc is not None else self.q
        self.cbm_handling = (_align(cbm_for_handling, "cbm_for_handling")
                             if cbm_for_handling is not None else self.q)

        self.I_bar = float(i_bar)
        self.s = float(s_rate)
        self.h = float(h_rate)
        self.Q = float(self.w_svc.sum())

        # validate service weights
        if (self.w_svc < 0).any() or not self.Q > 0:
            raise ValueError("w_svc must be non-negative with positive sum")

        self.handling_cost = self.h * float(self.cbm_handling.sum())  # independent of S

        self._C_vals = self.C.values
        self._dist_vals = self.D.values
        self._dist_cols = self.D.columns
        self._col_pos = {c: i for i, c in enumerate(self.C.columns)}

    # ------------------------------------------------------------------
    def storage_cost(self, K):
        """Storage = s * I_bar * sqrt(K). More DCs -> LESS pooling -> HIGHER cost."""
        return self.s * self.I_bar * np.sqrt(K)

    def make_weights(self, w_obj=None):
        """Objective weights as a numpy array with mean 1 (Section 9.2). None -> all ones."""
        if w_obj is None:
            return np.ones(len(self.C.index))
        w = w_obj.reindex(self.C.index)
        if w.isna().any():
            raise ValueError("w_obj has missing branches")
        if (w < 0).any() or w.mean() <= 0:
            raise ValueError("w_obj must be non-negative with positive mean")
        return (w / w.mean()).values

    def _check_open_set(self, S, K):
        if len(S) != K or len(set(S)) != K:
            raise ValueError(f"Expected {K} distinct DCs, got {len(set(S))}: {S}")
        unknown = set(S) - set(self._col_pos)
        if unknown:
            raise ValueError(f"Open DC not in candidate set: {unknown}")

    def _validate_solution(self, S, K, assignments):
        """Feasibility checks (Section 15.2)."""
        self._check_open_set(S, K)
        if len(assignments) != len(self.C):
            raise ValueError(f"Not every branch assigned: {len(assignments)} vs {len(self.C)}")
        if not assignments.index.is_unique:
            raise ValueError("Duplicate branch assignment")
        if assignments.isna().any():
            raise ValueError("NaN in assignment")
        if not set(assignments.unique()).issubset(set(S)):
            raise ValueError(f"Branch assigned to closed DC: {set(assignments.unique()) - set(S)}")

    # ------------------------------------------------------------------
    def fast_delivery(self, S, wn=None):
        """
        Delivery objective Z(S) = sum_i wn_i * min_{j in S} c_ij, numpy only.
        For heuristic loops. wn = make_weights(w_obj) (None -> equal-frequency).
        """
        S = list(S)
        self._check_open_set(S, len(S))
        lane = self._C_vals[:, [self._col_pos[j] for j in S]].min(axis=1)
        return float(lane.sum() if wn is None else (lane * wn).sum())

    # ------------------------------------------------------------------
    def evaluate(self, S, K=None, w_obj=None, quiet=True):
        """
        S     : list of open DC ids
        K     : number of open DCs (defaults to len(S); if given, must match)
        w_obj : optional Series of branch weights for the delivery objective
                (None = equal-frequency proxy, S0)
        Returns (metrics dict, assignments Series branch -> dc_id)

        delivery_cost           : equal-frequency lane-cost proxy (always)
        delivery_cost_weighted  : normalized weighted proxy (= delivery_cost if w_obj is None)
        delivery_objective      : the scenario's objective (weighted if w_obj given)
        total_modeled_cost      : delivery_objective + storage + handling (follows the scenario)
        """
        S = list(S)
        if K is None:
            K = len(S)

        # Check S before indexing so errors are clear
        self._check_open_set(S, K)

        # Deterministic tie-break: order S by candidate-column order, so the same
        # set of DCs always gives the same assignment regardless of input order.
        S_set = set(S)
        S_ord = [c for c in self.C.columns if c in S_set]

        sub_cost = self.C[S_ord]
        assignments = sub_cost.idxmin(axis=1)
        self._validate_solution(S, K, assignments)

        # ---- Delivery cost ----
        lane_costs = sub_cost.min(axis=1)
        wn = self.make_weights(w_obj)

        delivery_cost = float(lane_costs.sum())
        delivery_cost_weighted = float((lane_costs.values * wn).sum())
        delivery_obj = delivery_cost if w_obj is None else delivery_cost_weighted

        # ---- Storage + handling ----
        storage_cost = self.storage_cost(K)
        handling_cost = self.handling_cost
        total_modeled_cost = delivery_obj + storage_cost + handling_cost

        # ---- Assigned distances ----
        dc_idx = self._dist_cols.get_indexer(assignments.values)
        dist_assigned = pd.Series(
            self._dist_vals[np.arange(len(assignments)), dc_idx],
            index=assignments.index,
        )

        # Service metrics
        w = self.w_svc
        weighted_mean_km = float((w * dist_assigned).sum() / self.Q)

        order = dist_assigned.sort_values(kind="stable").index
        cum_ratio = (w.loc[order].cumsum() / self.Q).values
        idx_p95 = int(np.argmax(cum_ratio >= 0.95 - 1e-12))
        weighted_p95_km = float(dist_assigned.loc[order].iloc[idx_p95])

        cov_250 = float(w[dist_assigned <= 250].sum() / self.Q)
        cov_500 = float(w[dist_assigned <= 500].sum() / self.Q)
        max_dist = float(dist_assigned.max())

        metrics = {
            "k": K,
            "delivery_cost": delivery_cost,
            "delivery_cost_weighted": delivery_cost_weighted,
            "delivery_objective": delivery_obj,
            "storage_cost": storage_cost,
            "handling_cost": handling_cost,
            "total_modeled_cost": total_modeled_cost,
            "weighted_mean_km": weighted_mean_km,
            "weighted_p95_km": weighted_p95_km,
            "coverage_250": cov_250,
            "coverage_500": cov_500,
            "max_distance_km": max_dist,
        }

        # ---- Invariants ----
        assert np.isclose(total_modeled_cost, delivery_obj + storage_cost + handling_cost), \
            "Cost components don't reconcile"
        assert 0 <= cov_250 <= cov_500 <= 1 + 1e-12, \
            f"Coverage invalid: 250={cov_250}, 500={cov_500}"
        assert weighted_p95_km <= max_dist + 1e-9, \
            f"P95 ({weighted_p95_km}) > max dist ({max_dist})"

        if not quiet:
            print("\n[ COST BREAKDOWN (AUD) ]")
            print(f"  Delivery (unweighted) : {delivery_cost:,.3f}")
            print(f"  Delivery (weighted)   : {delivery_cost_weighted:,.3f}")
            print(f"  Storage (sqrt rule)   : {storage_cost:,.3f}")
            print(f"  Handling              : {handling_cost:,.3f}")
            print(f"  TOTAL MODELED COST    : {total_modeled_cost:,.3f}")
            print("\n[ SERVICE PERFORMANCE ]")
            print(f"  Mean Wt. Distance     : {weighted_mean_km:,.3f} km")
            print(f"  P95 Wt. Distance      : {weighted_p95_km:,.3f} km")
            print(f"  Max Assigned Distance : {max_dist:,.3f} km")
            print(f"  Coverage (<= 250km)   : {cov_250:.3%}")
            print(f"  Coverage (<= 500km)   : {cov_500:.3%}")

        return metrics, assignments


