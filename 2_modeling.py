def brute_force(matrix, K):
    best_obj, best_S = np.inf, None
    for subset in itertools.combinations(matrix.columns, K):
        z = matrix[list(subset)].min(axis=1).sum()
        if z < best_obj:
            best_obj, best_S = z, list(subset)
    return best_S, float(best_obj)

