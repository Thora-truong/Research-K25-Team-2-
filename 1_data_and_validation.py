def calculate_haversine_matrix(df_origins, df_destinations, stretch_factor=1.0):
    R = 6371.0088  # Bán kính Trái Đất (km)

    lat1 = np.radians(df_origins["Latitude"].values)[:, np.newaxis]
    lon1 = np.radians(df_origins["Longitude"].values)[:, np.newaxis]
    lat2 = np.radians(df_destinations["Latitude"].values)[np.newaxis, :]
    lon2 = np.radians(df_destinations["Longitude"].values)[np.newaxis, :]

    dlat = lat2 - lat1
    dlon = lon2 - lon1

    a = (
        np.sin(dlat / 2.0) ** 2
        + np.cos(lat1) * np.cos(lat2) * np.sin(dlon / 2.0) ** 2
    )
    c = 2 * np.arcsin(np.sqrt(a))

    return R * c * stretch_factor

