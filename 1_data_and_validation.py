def calculate_delivery_cost(distance):
    for _, row in nsw_curves.iterrows():
        min_d = row["Min Distance (KM)"]
        max_d = row["Max Distance (KM)"]
        if min_d <= distance < max_d or (distance == max_d):
            return row["Intercept (AUD)"] + row["Slope (AUD/KM)"] * distance
    last_row = nsw_curves.iloc[-1]
    return last_row["Intercept (AUD)"] + last_row["Slope (AUD/KM)"] * distance


